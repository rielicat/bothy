// Command typesgen runs tygo over the packages in tools/tygo.yaml and merges
// the results into one TypeScript file (web/src/lib/api/types.gen.ts).
//
//	cd tools && go run ./typesgen -root ..
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/gzuidhof/tygo/tygo"
	"golang.org/x/tools/go/packages"
	"gopkg.in/yaml.v2"
)

type config struct {
	Output       string                `yaml:"output"`
	TypeMappings map[string]string     `yaml:"type_mappings"`
	Packages     []*tygo.PackageConfig `yaml:"packages"`
	Overrides    map[string]string     `yaml:"overrides"`
	Renames      map[string]string     `yaml:"renames"`
}

type pkgInfo struct {
	conf    *tygo.PackageConfig
	name    string
	dir     string // relative to the repo root
	types   []string
	structs map[string]bool
	embeds  []embed
}

// embed is an untagged embedded struct field. encoding/json flattens its
// fields into the owner, which tygo only models with a `tstype:",extends"` tag.
type embed struct {
	owner, field, pkg, typ string
}

func main() {
	root := flag.String("root", "..", "repository root (packages resolve against its go.mod)")
	cfgPath := flag.String("config", "tygo.yaml", "typesgen/tygo config")
	flag.Parse()
	if err := run(*root, *cfgPath); err != nil {
		fmt.Fprintln(os.Stderr, "typesgen:", err)
		os.Exit(1)
	}
}

func run(root, cfgPath string) error {
	raw, err := os.ReadFile(cfgPath)
	if err != nil {
		return err
	}
	var cfg config
	if err := yaml.UnmarshalStrict(raw, &cfg); err != nil {
		return fmt.Errorf("%s: %w", cfgPath, err)
	}
	if cfg.Output == "" || len(cfg.Packages) == 0 {
		return errors.New("config needs output and packages")
	}
	// tygo loads packages relative to the working directory, which must be the
	// root module rather than tools/.
	if err := os.Chdir(root); err != nil {
		return err
	}
	wd, err := os.Getwd()
	if err != nil {
		return err
	}
	infos, err := inspect(wd, cfg.Packages)
	if err != nil {
		return err
	}
	byName := map[string]*pkgInfo{}
	for _, p := range infos {
		byName[p.name] = p
	}
	finalName := func(pkg, typ string) string {
		if n, ok := cfg.Renames[pkg+"."+typ]; ok {
			return n
		}
		return typ
	}

	// Cross-package references are written as opaque markers first so that a
	// rename applied to one package's text cannot hit another package's type.
	var refs []string
	markers := map[string]string{}
	for _, q := range infos {
		for _, t := range q.types {
			markers[q.name+"."+t] = fmt.Sprintf("__REF%d__", len(refs))
			refs = append(refs, finalName(q.name, t))
		}
	}
	tmp, err := os.MkdirTemp("", "typesgen")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	for i, p := range infos {
		m := map[string]string{}
		for _, src := range []map[string]string{cfg.TypeMappings, markers, p.conf.TypeMappings} {
			for k, v := range src {
				m[k] = v
			}
		}
		p.conf.TypeMappings = m
		p.conf.OutputPath = filepath.Join(tmp, fmt.Sprintf("%d.ts", i))
	}
	if err := tygo.New(&tygo.Config{Packages: cfg.Packages}).Generate(); err != nil {
		return err
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by tools/typesgen (tygo) from tools/tygo.yaml. DO NOT EDIT.\n")
	out.WriteString("// Regenerate with `make gen`.\n")
	overridden := map[string]bool{}
	for _, p := range infos {
		b, err := os.ReadFile(p.conf.OutputPath)
		if err != nil {
			return err
		}
		body := strings.TrimPrefix(string(b), "// Code generated by tygo. DO NOT EDIT.\n")
		body = sourceLine.ReplaceAllString(body, "// source: "+filepath.ToSlash(p.dir)+"/$1")
		for _, from := range sortedKeys(cfg.Renames) {
			pkg, typ, ok := strings.Cut(from, ".")
			if !ok {
				return fmt.Errorf("rename %q: want <package>.<Type>", from)
			}
			if pkg == p.name {
				body = regexp.MustCompile(`\b`+regexp.QuoteMeta(typ)+`\b`).ReplaceAllString(body, cfg.Renames[from])
			}
		}
		body = refMarker.ReplaceAllStringFunc(body, func(m string) string {
			n, _ := strconv.Atoi(strings.TrimSuffix(strings.TrimPrefix(m, "__REF"), "__"))
			return refs[n]
		})
		for _, e := range p.embeds {
			if q := byName[e.pkg]; q == nil || !q.structs[e.typ] {
				continue
			}
			if body, err = flatten(body, finalName(p.name, e.owner), e.field, finalName(e.pkg, e.typ)); err != nil {
				return err
			}
		}
		for _, typ := range sortedKeys(cfg.Overrides) {
			var hit bool
			if body, hit = override(body, typ, cfg.Overrides[typ]); hit {
				overridden[typ] = true
			}
		}
		out.WriteString(body)
	}
	for typ := range cfg.Overrides {
		if !overridden[typ] {
			return fmt.Errorf("override %s: no such declaration", typ)
		}
	}
	if dups := duplicates(out.String()); len(dups) > 0 {
		return fmt.Errorf("declared by more than one package (add renames): %s", strings.Join(dups, ", "))
	}

	dst := filepath.FromSlash(cfg.Output)
	if old, err := os.ReadFile(dst); err == nil && bytes.Equal(old, out.Bytes()) {
		return nil
	}
	return os.WriteFile(dst, out.Bytes(), 0o644) //nolint:gosec // a committed source file, not a secret
}

var (
	sourceLine = regexp.MustCompile(`(?m)^// source: (\S+)$`)
	declared   = regexp.MustCompile(`(?m)^export (?:type|interface|const|enum) (\w+)`)
	refMarker  = regexp.MustCompile(`__REF\d+__`)
)

// override replaces the declaration of typ (alias or interface form) with
// ts and drops consts typed as typ, whose values no longer fit.
func override(body, typ, ts string) (string, bool) {
	q := regexp.QuoteMeta(typ)
	decl := regexp.MustCompile(`(?ms)^export (?:type ` + q + ` = [^;]*;[^\n]*|interface ` + q + ` \{.*?^\})$`)
	if !decl.MatchString(body) {
		return body, false
	}
	body = decl.ReplaceAllLiteralString(body, "export type "+typ+" = "+ts+";")
	consts := regexp.MustCompile(`(?m)^export const \w+: ` + q + ` = .*\n`)
	return consts.ReplaceAllString(body, ""), true
}

// flatten turns the field tygo emitted for an embedded struct into `extends`.
func flatten(body, owner, field, ts string) (string, error) {
	block := regexp.MustCompile(`(?ms)^export interface ` + regexp.QuoteMeta(owner) + `(<[^>\n]*>)?( extends [^{\n]*)? \{\n.*?^\}`)
	loc := block.FindStringSubmatchIndex(body)
	if loc == nil {
		return "", fmt.Errorf("embed %s in %s: interface not found", ts, owner)
	}
	text := body[loc[0]:loc[1]]
	line := regexp.MustCompile(`(?m)^  ` + regexp.QuoteMeta(field) + `\??: ` + regexp.QuoteMeta(ts) + `;[^\n]*\n`)
	if !line.MatchString(text) {
		return "", fmt.Errorf("embed %s in %s: field not found", ts, owner)
	}
	text = line.ReplaceAllString(text, "")
	var generics, ext string
	if loc[2] >= 0 {
		generics = body[loc[2]:loc[3]]
	}
	if loc[4] >= 0 {
		ext = body[loc[4]:loc[5]] + ", " + ts
	} else {
		ext = " extends " + ts
	}
	head := "export interface " + owner + generics
	text = head + ext + text[strings.Index(text, " {\n"):]
	return body[:loc[0]] + text + body[loc[1]:], nil
}

func duplicates(ts string) []string {
	seen := map[string]int{}
	for _, m := range declared.FindAllStringSubmatch(ts, -1) {
		seen[m[1]]++
	}
	var dups []string
	for n, c := range seen {
		if c > 1 {
			dups = append(dups, n)
		}
	}
	sort.Strings(dups)
	return dups
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// inspect collects what each package contributes (exported types, structs,
// embedded struct fields), honouring include_files/exclude_files like tygo.
func inspect(wd string, confs []*tygo.PackageConfig) ([]*pkgInfo, error) {
	paths := make([]string, len(confs))
	for i, c := range confs {
		paths[i] = c.Path
	}
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax}, paths...)
	if err != nil {
		return nil, err
	}
	byPath := map[string]*packages.Package{}
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			return nil, fmt.Errorf("%s: %v", p.PkgPath, p.Errors)
		}
		byPath[p.PkgPath] = p
	}
	infos := make([]*pkgInfo, len(confs))
	for i, c := range confs {
		p, ok := byPath[c.Path]
		if !ok || len(p.GoFiles) == 0 {
			return nil, fmt.Errorf("%s: package not found", c.Path)
		}
		dir, err := filepath.Rel(wd, filepath.Dir(p.GoFiles[0]))
		if err != nil {
			return nil, err
		}
		info := &pkgInfo{conf: c, name: p.Name, dir: dir, structs: map[string]bool{}}
		for j, f := range p.Syntax {
			if c.IsFileIgnored(p.GoFiles[j]) {
				continue
			}
			for _, d := range f.Decls {
				g, ok := d.(*ast.GenDecl)
				if !ok || g.Tok != token.TYPE {
					continue
				}
				for _, s := range g.Specs {
					ts := s.(*ast.TypeSpec)
					if !ts.Name.IsExported() {
						continue
					}
					info.types = append(info.types, ts.Name.Name)
					if st, ok := ts.Type.(*ast.StructType); ok {
						info.structs[ts.Name.Name] = true
						info.embeds = append(info.embeds, embeds(p.Name, ts.Name.Name, st)...)
					}
				}
			}
		}
		infos[i] = info
	}
	return infos, nil
}

func embeds(pkg, owner string, st *ast.StructType) []embed {
	var out []embed
	for _, f := range st.Fields.List {
		if len(f.Names) > 0 {
			continue
		}
		if f.Tag != nil {
			tag, _ := strconv.Unquote(f.Tag.Value)
			if name, _, _ := strings.Cut(reflect.StructTag(tag).Get("json"), ","); name != "" {
				continue // a named JSON field, not flattened
			}
		}
		t := f.Type
		if star, ok := t.(*ast.StarExpr); ok {
			t = star.X
		}
		switch x := t.(type) {
		case *ast.Ident:
			out = append(out, embed{owner: owner, field: x.Name, pkg: pkg, typ: x.Name})
		case *ast.SelectorExpr:
			if id, ok := x.X.(*ast.Ident); ok {
				out = append(out, embed{owner: owner, field: x.Sel.Name, pkg: id.Name, typ: x.Sel.Name})
			}
		}
	}
	return out
}
