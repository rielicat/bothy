func TestGitignorePatterns(t *testing.T) {
	ig := &ignorer{dirs: map[string]ruleSet{
		"": parseIgnore("", []byte(strings.Join([]string{
			"# comment", "", "*.log", "!keep.log", "/build", "out/", "docs/**/*.tmp", "**/cache", "secret?.txt",
			"data/**", "!data/schema.sql", "[!a]x.cfg", `\#hash`, "trailing   ", "/a/b", "logs/",
		}, "\n"))),
		"pkg": parseIgnore("pkg", []byte("gen/\n*.pb\n!important.pb\n/local.txt\n")),
	}}
	cases := []struct {
		path  string
		dir   bool
		want  bool
		label string
	}{
		{"app.log", false, true, "glob at root"},
		{"sub/x/app.log", false, true, "unanchored glob at any depth"},
		{"keep.log", false, false, "negation"},
		{"build", true, true, "anchored dir"},
		{"src/build", true, false, "anchored pattern only at its base"},
		{"out", true, true, "dir-only pattern on a dir"},
		{"out", false, false, "dir-only pattern on a file"},
		{"docs/a/b/x.tmp", false, true, "** in the middle"},
		{"docs/x.tmp", false, true, "** matches zero dirs"},
		{"deep/er/cache", true, true, "leading **"},
		{"secret1.txt", false, true, "? wildcard"},
		{"secret10.txt", false, false, "? is one character"},
		{"data/rows.csv", false, true, "trailing ** matches inside"},
		{"data", true, false, "trailing ** does not match the dir itself"},
		{"data/schema.sql", false, false, "re-include under trailing **"},
		{"bx.cfg", false, true, "[!a] class"},
		{"ax.cfg", false, false, "[!a] excludes a"},
		{"#hash", false, true, "escaped #"},
		{"trailing", false, true, "trailing spaces trimmed"},
		{"a/b", false, true, "anchored path"},
		{"x/a/b", false, false, "anchored path elsewhere"},
		{"pkg/gen", true, true, "nested .gitignore dir"},
		{"pkg/sub/x.pb", false, true, "nested unanchored glob"},
		{"pkg/important.pb", false, false, "nested negation"},
		{"pkg/local.txt", false, true, "nested anchored"},
		{"pkg/sub/local.txt", false, false, "nested anchored only at its base"},
		{"other/x.pb", false, false, "nested rules stay in their dir"},
		{"main.go", false, false, "unmatched"},
	}
	for _, c := range cases {
		if got := ig.ignored(c.path, c.dir); got != c.want {
			t.Errorf("%s: ignored(%q, dir=%v) = %v, want %v", c.label, c.path, c.dir, got, c.want)
		}
	}
}

