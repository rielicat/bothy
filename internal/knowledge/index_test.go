func TestIndexFiltersAndIsIncremental(t *testing.T) {
	h := newHarness(t, func(c *config.Config) { c.Knowledge.MaxFileKB = 1 })
	h.writeRepo()
	outside := t.TempDir()
	if err := os.WriteFile(filepath.Join(outside, "host.txt"), []byte("zanzibar host secret\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	links := os.Symlink(filepath.Join(outside, "host.txt"), filepath.Join(h.ws, "repos/acme/api/link.txt")) == nil &&
		os.Symlink(outside, filepath.Join(h.ws, "repos/acme/api/linkdir")) == nil

	r := h.index("repos/acme/api", "acme/api", "aaaaaaa1")
	if r.Status != core.IndexReady || r.Error != "" {
		t.Fatalf("index = %s %q", r.Status, r.Error)
	}
	want := []string{".gitignore", "README.md", "limit.go", "main.go", "old.go"}
	if got := h.paths(r.ID); !slices.Equal(got, want) {
		t.Fatalf("indexed %v, want %v", got, want)
	}
	if r.Files != 5 || r.Skipped != 1 || r.Truncated || r.Chunks == 0 || r.Bytes == 0 || r.IndexedAt.IsZero() {
		t.Fatalf("stats = %+v", r)
	}
	hits, err := h.svc.Search(h.ctx, h.viewer(), core.KnowledgeQuery{Text: "zanzibar"})
	if err != nil || len(hits) != 0 {
		t.Fatalf("ignored, vendored, generated, binary, oversized or linked content was indexed: %+v %v (links=%v)", hits, err, links)
	}
	h.repo.take()

	h.write("repos/acme/api/main.go", "package main\n\nfunc main() {\n\tserveTLS()\n}\n")
	h.write("repos/acme/api/new.go", "package main\n\nfunc New() {}\n")
	if err := os.Remove(filepath.Join(h.ws, "repos/acme/api/old.go")); err != nil {
		t.Fatal(err)
	}
	r2, err := h.svc.Reindex(h.ctx, h.viewer(), r.ID, h.user.ID)
	if err != nil {
		t.Fatal(err)
	}
	if r2.Status != core.IndexQueued {
		t.Fatalf("reindex status = %s", r2.Status)
	}
	r2 = h.runJob(r.ID)
	if got := h.repo.take(); !slices.Equal(got, []string{"main.go", "new.go", "-old.go"}) {
		t.Fatalf("re-index applied %v; want only the changed, new and deleted files", got)
	}
	if r2.Files != 5 || r2.Status != core.IndexReady {
		t.Fatalf("after re-index = %+v", r2)
	}
	chunks, err := h.repo.Chunks(h.ctx, core.SystemViewer(), r.ID, "limit.go")
	if err != nil || len(chunks) == 0 || chunks[0].SHA != "aaaaaaa1" {
		t.Fatalf("unchanged chunks = %+v %v", chunks, err)
	}
	h.repo.take()
	if h.runJob(r.ID); len(h.repo.take()) != 0 {
		t.Fatal("an unchanged tree was re-applied")
	}
}

func TestIndexRelabelsChunksWithTheNewCommit(t *testing.T) {
	h := newHarness(t)
	h.writeRepo()
	first := h.index("repos/acme/api", "acme/api", "aaaaaaa1")
	h.write("repos/acme/api/main.go", "package main\n\nfunc main() { other() }\n")
	r, err := h.svc.enqueue(h.ctx, h.p, "acme/api", "repos/acme/api", "bbbbbbb2", core.KnowledgeGitHub)
	if err != nil {
		t.Fatal(err)
	}
	r = h.runJob(r.ID)
	all, err := h.repo.Chunks(h.ctx, core.SystemViewer(), r.ID, "")
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range all {
		if c.SHA != "bbbbbbb2" {
			t.Fatalf("chunk %s:%d still cites %s", c.Path, c.StartLine, c.SHA)
		}
	}
	if r.ID != first.ID || r.SHA != "bbbbbbb2" || r.Source != core.KnowledgeGitHub {
		t.Fatalf("repo = %+v", r)
	}
}

func TestIndexCaps(t *testing.T) {
	h := newHarness(t, func(c *config.Config) { c.Knowledge.MaxFiles = 2 })
	for _, n := range []string{"a", "b", "c", "d"} {
		h.write("proj/"+n+".txt", "file "+n+"\n")
	}
	r := h.index("proj", "", "")
	if r.Repo != "local/proj" || r.Files != 2 || !r.Truncated || r.Status != core.IndexReady {
		t.Fatalf("capped index = %+v", r)
	}
	if got := h.paths(r.ID); !slices.Equal(got, []string{"a.txt", "b.txt"}) {
		t.Fatalf("indexed %v", got)
	}
}

func TestIndexNeverWritesIntoTheRepo(t *testing.T) {
	h := newHarness(t, func(c *config.Config) { c.Knowledge.AutoNotes = true })
	h.writeRepo()
	h.llm.Steps = append(h.llm.Steps, draftStep("## Summary\nThe acme API.\n"))
	before := snapshotTree(t, h.ws)
	r := h.index("repos/acme/api", "acme/api", "")
	h.svc.bgWG.Wait()
	if after := snapshotTree(t, h.ws); len(after) != len(before) {
		t.Fatalf("workspace changed: %d files before, %d after", len(before), len(after))
	} else {
		for k, v := range before {
			if after[k] != v {
				t.Fatalf("workspace file %s changed", k)
			}
		}
	}
	notes := filepath.Join(h.data, "knowledge", string(h.p.ID), "acme", "api", "NOTES.md")
	if _, err := os.Stat(notes); err != nil {
		t.Fatalf("notes not written outside the repo: %v (repo %+v)", err, r)
	}
}

func TestIndexDirectoryErrors(t *testing.T) {
	h := newHarness(t)
	for _, dir := range []string{"../escape", "/etc", "missing/dir"} {
		_, err := h.svc.Index(h.ctx, h.viewer(), h.p.ID, core.KnowledgeIndexRequest{Dir: dir}, h.user.ID)
		if !errors.Is(err, core.ErrInvalid) {
			t.Errorf("Index(%q) = %v, want ErrInvalid", dir, err)
		}
	}
	h.write("gone/a.txt", "x\n")
	r, err := h.svc.Index(h.ctx, h.viewer(), h.p.ID, core.KnowledgeIndexRequest{Dir: "gone"}, h.user.ID)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.RemoveAll(filepath.Join(h.ws, "gone")); err != nil {
		t.Fatal(err)
	}
	r = h.runJob(r.ID)
	if r.Status != core.IndexFailed || !strings.Contains(r.Error, "gone is not in the workspace") {
		t.Fatalf("vanished dir = %s %q", r.Status, r.Error)
	}
	if _, err := h.svc.Index(h.ctx, h.viewer(), h.p.ID, core.KnowledgeIndexRequest{Dir: ".", Repo: "not a repo"}, h.user.ID); !errors.Is(err, core.ErrInvalid) {
		t.Errorf("bad repo name = %v", err)
	}
	if _, err := h.svc.Index(h.ctx, h.viewer(), h.p.ID, core.KnowledgeIndexRequest{Dir: ".", SHA: "zz"}, h.user.ID); !errors.Is(err, core.ErrInvalid) {
		t.Errorf("bad sha = %v", err)
	}
}
