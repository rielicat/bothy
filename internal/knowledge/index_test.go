func (h *harness) paths(id int64) []string {
	h.t.Helper()
	files, err := h.repo.Files(h.ctx, core.SystemViewer(), id)
	if err != nil {
		h.t.Fatal(err)
	}
	var out []string
	for _, f := range files {
		out = append(out, f.Path)
	}
	return out
}

